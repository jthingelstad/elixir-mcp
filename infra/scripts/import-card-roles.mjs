#!/usr/bin/env node
/**
 * Import the deck-archetype vocabulary from the sibling cr-agent-api-docs
 * checkout into the record (docs/reviews/2026-09-20-DECK-ARCHETYPES-DESIGN.md
 * §12.4). The Lambdas have no internet, so the operator's machine reads
 * ../cr-agent-api-docs/data/card-roles.json and data/deck-aliases.json,
 * refuses a dirty or unpushed sibling (the version must be a commit
 * anyone can read), sends the rows to the migrate Lambda
 * ({card_roles_import}), and refreshes fixtures/card-roles.snapshot.json
 * so the tests run in CI without the sibling. Run by deploy.mjs after
 * migrations; runnable alone:
 *
 *   AWS_PROFILE=cloud-engineer node infra/scripts/import-card-roles.mjs
 *   node infra/scripts/import-card-roles.mjs --snapshot-only   (no AWS)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
const sibling = path.resolve(repoRoot, "../cr-agent-api-docs");
const snapshotPath = path.join(repoRoot, "fixtures/card-roles.snapshot.json");

function git(...args) {
  return execFileSync("git", ["-C", sibling, ...args], {
    encoding: "utf8",
  }).trim();
}

export function readVocabulary() {
  const roles = JSON.parse(
    readFileSync(path.join(sibling, "data/card-roles.json"), "utf8"),
  );
  const aliases = JSON.parse(
    readFileSync(path.join(sibling, "data/deck-aliases.json"), "utf8"),
  );
  const dirty = git(
    "status",
    "--porcelain",
    "--",
    "data/card-roles.json",
    "data/deck-aliases.json",
  );
  if (dirty)
    throw new Error(
      `cr-agent-api-docs vocabulary has uncommitted changes:\n${dirty}`,
    );
  const source_commit = git("rev-parse", "HEAD");
  // The version is the vocabulary's last commit time, in UTC.
  const roles_version = new Date(
    Number(
      git(
        "log",
        "-1",
        "--format=%ct",
        "--",
        "data/card-roles.json",
        "data/deck-aliases.json",
      ),
    ) * 1000,
  ).toISOString();
  return {
    roles: roles.roles,
    aliases: aliases.aliases,
    unattested: roles.unattested ?? [],
    roles_version,
    source_commit,
  };
}

const vocabulary = readVocabulary();
writeFileSync(
  snapshotPath,
  JSON.stringify(
    {
      note: "Generated by infra/scripts/import-card-roles.mjs from ../cr-agent-api-docs; the tests' copy of the vocabulary. Edit the source files there, never this.",
      ...vocabulary,
    },
    null,
    2,
  ) + "\n",
);
console.error(
  `snapshot: ${vocabulary.roles.length} roles, ${vocabulary.aliases.length} aliases, version ${vocabulary.roles_version} (${vocabulary.source_commit.slice(0, 7)})`,
);

if (!process.argv.includes("--snapshot-only")) {
  const { LambdaClient, InvokeCommand } =
    await import("@aws-sdk/client-lambda");
  const lambda = new LambdaClient({ region: "us-east-1" });
  const { roles, aliases, roles_version, source_commit } = vocabulary;
  const invoked = await lambda.send(
    new InvokeCommand({
      FunctionName: "elixir-mcp-migrate",
      Payload: JSON.stringify({
        card_roles_import: { roles, aliases, roles_version, source_commit },
      }),
    }),
  );
  const result = JSON.parse(Buffer.from(invoked.Payload).toString() || "null");
  if (invoked.FunctionError) {
    console.error(`IMPORT FAILED: ${JSON.stringify(result)}`);
    process.exit(1);
  }
  console.error(`imported: ${JSON.stringify(result)}`);
}
