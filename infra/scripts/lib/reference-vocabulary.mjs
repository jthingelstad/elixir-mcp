import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../..");
const sibling = path.resolve(repoRoot, "../cr-agent-api-docs");

function git(...args) {
  return execFileSync("git", ["-C", sibling, ...args], {
    encoding: "utf8",
  }).trim();
}

export function readVocabulary() {
  const dirty = git(
    "status",
    "--porcelain",
    "--",
    "data/card-roles.json",
    "data/deck-aliases.json",
  );
  if (dirty)
    throw new Error(
      `cr-agent-api-docs vocabulary has uncommitted changes:\n${dirty}`,
    );
  // The commit that last changed the vocabulary, not the sibling's HEAD:
  // any later commit there (a doc, a probe) used to move source_commit,
  // so every deploy rewrote the committed snapshot and left the tracked
  // tree dirty (2026-11-13). At this commit the two files are what HEAD
  // holds (the check above refused anything uncommitted), and the
  // snapshot now moves only when the vocabulary does.
  const source_commit = git(
    "log",
    "-1",
    "--format=%H",
    "HEAD",
    "--",
    "data/card-roles.json",
    "data/deck-aliases.json",
  );
  const roles = JSON.parse(
    git("show", `${source_commit}:data/card-roles.json`),
  );
  const aliases = JSON.parse(
    git("show", `${source_commit}:data/deck-aliases.json`),
  );
  // The version is the vocabulary's last commit time, in UTC.
  const roles_version = new Date(
    Number(git("log", "-1", "--format=%ct", source_commit)) * 1000,
  ).toISOString();
  return {
    roles: roles.roles,
    aliases: aliases.aliases,
    unattested: roles.unattested ?? [],
    roles_version,
    source_commit,
  };
}

export const SNAPSHOT_PATH = path.join(
  repoRoot,
  "fixtures/card-roles.snapshot.json",
);

/** The snapshot's text for a vocabulary: a pure function of it. */
export function snapshotText(vocabulary) {
  return (
    JSON.stringify(
      {
        note: "Generated by infra/scripts/import-card-roles.mjs from ../cr-agent-api-docs; the tests' copy of the vocabulary. Edit the source files there, never this.",
        ...vocabulary,
      },
      null,
      2,
    ) + "\n"
  );
}

/** Whether the committed snapshot already says what `vocabulary` says.
 *  The deploy only asks; writing it is the explicit refresh's job
 *  (`import-card-roles.mjs --snapshot-only`), landed by pull request. */
export function snapshotIsCurrent(vocabulary, file = SNAPSHOT_PATH) {
  try {
    return readFileSync(file, "utf8") === snapshotText(vocabulary);
  } catch {
    return false;
  }
}

/** The explicit refresh: writes the committed snapshot. Never called by
 *  a deploy, which must not change a tracked file. */
export function saveVocabularySnapshot(vocabulary, file = SNAPSHOT_PATH) {
  writeFileSync(file, snapshotText(vocabulary));
  console.error(
    `snapshot: ${vocabulary.roles.length} roles, ${vocabulary.aliases.length} aliases, version ${vocabulary.roles_version} (${vocabulary.source_commit.slice(0, 7)})`,
  );
}
